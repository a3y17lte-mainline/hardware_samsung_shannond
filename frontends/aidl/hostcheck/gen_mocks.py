"""Host-only stand-ins for the NDK headers of the radio HAL interfaces.

    gen_mocks.py AIDL_API_DIR VERSION OUT_DIR [AIDL_SOURCE_DIR...]

Writes aidl/android/hardware/radio/.../<Type>.h for every type of the frozen
API, and of our own interfaces' sources (which name every type in full, as
the API dumps do): parcelables as structs, unions over std::variant, enums as enum
classes, interfaces as abstract classes with a Bn class. Together with the
hand-written binder and libbase stand-ins next to this script, the AIDL
front end compiles on the host with -fsyntax-only, which catches wrong
names, types and signatures before an Android build. Nothing here runs.
"""
import re
import sys
from pathlib import Path

PRIMITIVES = {
    "int": "int32_t", "long": "int64_t", "boolean": "bool", "byte": "int8_t",
    "char": "char16_t", "float": "float", "double": "double", "void": "void",
}
BACKING = {"int": "int32_t", "long": "int64_t", "byte": "int8_t"}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def qualified(name):
    return "::aidl::" + name.replace(".", "::")


def cpp_type(aidl, kinds):
    nullable = "@nullable" in aidl
    aidl = re.sub(r"@\w+(\([^)]*\))?\s*", "", aidl).strip()
    array = aidl.endswith("[]")
    base = aidl[:-2] if array else aidl
    if base.startswith("List<"):
        array, base = True, base[5:-1]
    if base in PRIMITIVES:
        t = PRIMITIVES[base]
        if array and base == "byte":
            t = "uint8_t"
    elif base == "String":
        t = "std::string"
    elif base == "ParcelFileDescriptor":
        t = "::ndk::ScopedFileDescriptor"
    elif base in kinds:
        t = qualified(base)
        if kinds[base] == "interface":
            t = f"std::shared_ptr<{t}>"
    else:
        sys.exit(f"unknown type {aidl}")
    if array:
        t = f"std::vector<{t}>"
    if nullable and not t.startswith("std::shared_ptr"):
        t = f"std::optional<{t}>"
    by_value = not array and not nullable and (base in PRIMITIVES or kinds.get(base) == "enum")
    return t, by_value, base


def value(expr, numeric=False):
    expr = re.sub(r"\b(0x[0-9A-Fa-f]+|\d+)u8\b", r"static_cast<int8_t>(\1)", expr)
    # Dotted references to other types' constants and enumerators
    def ref(m):
        r = qualified(m.group(1)) + "::" + m.group(2)
        return f"static_cast<int64_t>({r})" if numeric else r
    expr = re.sub(r"\b((?:[a-z]\w*\.)+[A-Z][\w.]*)\.(\w+)\b", ref, expr)
    return expr.replace("{", "{").strip()


def deps(text, kinds, own, tops):
    found = set()
    for d in re.findall(r"\b((?:[a-z]\w*\.)+[A-Z][\w.]*)", text):
        # A nested type or an enumerator: the file that declares it
        while d not in tops and "." in d:
            d = d.rsplit(".", 1)[0]
        if d in tops and d != own:
            found.add(d)
    return sorted(found)


def header(pkg, name, includes, body):
    ns = pkg.split(".")
    lines = ["// Generated by gen_mocks.py for host syntax checks. Do not edit.", "#pragma once", "",
             "#include <array>", "#include <cstdint>", "#include <memory>", "#include <optional>",
             "#include <string>", "#include <variant>", "#include <vector>",
             '#include "ndk_mock.h"', ""]
    lines += [f"#include <{i}>" for i in includes]
    lines += ["", "namespace aidl::" + "::".join(ns) + " {", ""]
    lines += body
    lines += ["", "}  // namespace aidl::" + "::".join(ns), ""]
    return "\n".join(lines)


def body_of(text):
    """The declaration's body, past any annotation with braces in it"""
    m = re.search(r"\b(?:enum|parcelable|interface|union)\s+\w+[^{]*\{", text)
    return text[m.end():text.rindex("}")]


NESTED = re.compile(r"((?:@\w+(?:\([^)]*\))?\s*)*)\b(enum|parcelable|union)\s+(\w+)\s*\{([^{}]*)\}", re.S)


def split_nested(body):
    """Nested declarations (one level, as the radio API has) and the rest"""
    nested = [(m.group(2), m.group(3), m.group(1) + m.group(2) + " " + m.group(3) + " {" + m.group(4) + "}")
              for m in NESTED.finditer(body)]
    return nested, NESTED.sub("", body)


def path_of(full):
    return full.replace(".", "/") + ".h"


def gen_enum(name, text):
    backing = BACKING.get(re.search(r'@Backing\(type="(\w+)"\)', text).group(1), "int32_t") \
        if "@Backing" in text else "int8_t"
    body = body_of(text)
    items = [i.strip() for i in body.split(",") if i.strip()]
    out = [f"enum class {name} : {backing} {{"]
    for i in items:
        if "=" in i:
            n, v = i.split("=", 1)
            out.append(f"    {n.strip()} = static_cast<{backing}>({value(v, True)}),")
        else:
            out.append(f"    {i},")
    out.append("};")
    return out


def members(body, kinds):
    consts, fields = [], []
    for stmt in (s.strip() for s in body.split(";")):
        if not stmt:
            continue
        stmt = re.sub(r"^(@\w+(\([^)]*\))?\s+)+", lambda m: m.group(0) if "@nullable" in m.group(0) else "", stmt)
        if stmt.startswith("const "):
            m = re.match(r"const\s+(\S+)\s+(\w+)\s*=\s*(.+)$", stmt, re.S)
            t = m.group(1)
            if t == "String":
                consts.append(f"    static inline const char *{m.group(2)} = {m.group(3)};")
            else:
                consts.append(f"    static constexpr {PRIMITIVES[t]} {m.group(2)} = {value(m.group(3))};")
            continue
        m = re.match(r"(.+?)\s+(\w+)\s*(?:=\s*(.+))?$", stmt, re.S)
        if not m:
            continue
        t, by_value, base = cpp_type(m.group(1), kinds)
        default = m.group(3)
        fields.append((t.replace("const ", "").replace("&", ""), m.group(2), default, base))
    return consts, fields


def gen_nested(text, kinds):
    out = []
    nested, _ = split_nested(body_of(text))
    for kind, n, t in nested:
        sub = {"enum": gen_enum, "parcelable": gen_parcelable, "union": gen_union}[kind]
        out += ["    " + l for l in (sub(n, t) if kind == "enum" else sub(n, t, kinds))]
    return out


def gen_parcelable(name, text, kinds):
    nested = gen_nested(text, kinds)
    _, body = split_nested(body_of(text))
    consts, fields = members(body, kinds)
    out = [f"struct {name} {{"] + nested + consts
    for t, n, default, base in fields:
        if default is not None:
            d = value(default)
            if d.startswith("{"):
                out.append(f"    {t} {n} = {t}{d};")
            else:
                out.append(f"    {t} {n} = {d};")
        elif base in PRIMITIVES:
            out.append(f"    {t} {n} = {{}};")
        else:
            out.append(f"    {t} {n};")
    out.append(f"    bool operator==(const {name} &) const = default;")
    out.append("    std::string toString() const { return {}; }")
    out.append("};")
    return out


def gen_union(name, text, kinds):
    nested = gen_nested(text, kinds)
    _, body = split_nested(body_of(text))
    consts, fields = members(body, kinds)
    tags = ", ".join(n for _, n, _, _ in fields)
    types = ", ".join(t for t, _, _, _ in fields)
    out = [f"class {name} {{", "  public:"] + nested + consts + [
        f"    enum class Tag : int32_t {{ {tags} }};",
    ]
    for _, n, _, _ in fields:
        out.append(f"    static const inline Tag {n} = Tag::{n};")
    out += [
        f"    template <Tag _tag, typename... _Tp> static {name} make(_Tp &&...args) {{",
        f"        {name} u; u.set<_tag>(std::forward<_Tp>(args)...); return u; }}",
        "    Tag getTag() const { return static_cast<Tag>(value_.index()); }",
        "    template <Tag _tag> const auto &get() const { return std::get<static_cast<size_t>(_tag)>(value_); }",
        "    template <Tag _tag> auto &get() { return std::get<static_cast<size_t>(_tag)>(value_); }",
        "    template <Tag _tag, typename... _Tp> void set(_Tp &&...args) {",
        "        value_.template emplace<static_cast<size_t>(_tag)>(std::forward<_Tp>(args)...); }",
        f"    bool operator==(const {name} &) const = default;",
        "    std::string toString() const { return {}; }",
        "  private:",
        f"    std::variant<{types}> value_;",
        "};",
    ]
    return out


def gen_interface(name, text, kinds):
    body = body_of(text)
    out = [f"class {name} : public ::ndk::ICInterface {{", "  public:",
           f'    static inline const char *descriptor = "{name}";']
    methods = []
    for stmt in (s.strip() for s in body.split(";")):
        if not stmt:
            continue
        if stmt.startswith("const "):
            m = re.match(r"const\s+(\S+)\s+(\w+)\s*=\s*(.+)$", stmt, re.S)
            out.append(f"    static constexpr {PRIMITIVES.get(m.group(1), 'int32_t')} {m.group(2)} = {value(m.group(3))};")
            continue
        m = re.match(r"(?:oneway\s+)?(\S+)\s+(\w+)\s*\((.*)\)$", stmt, re.S)
        if not m:
            continue
        ret = m.group(1)
        params = []
        for p in filter(None, (s.strip() for s in m.group(3).split(","))):
            p = re.sub(r"^(in|out|inout)\s+", "", p)
            ptype, pname = p.rsplit(None, 1)
            t, by_value, _ = cpp_type(ptype, kinds)
            params.append(f"{t} {pname}" if by_value else f"const {t}& {pname}")
        if ret != "void":
            params.append(f"{cpp_type(ret, kinds)[0]}* _aidl_return")
        methods.append(f"    virtual ::ndk::ScopedAStatus {m.group(2)}({', '.join(params)}) = 0;")
    out += methods + ["};"]
    return out


def generate(api, version, out, sources=()):
    files = {}
    dirs = list(sources)
    for pkgdir in api.iterdir():
        vdir = pkgdir / str(version)
        if not vdir.is_dir():
            versions = sorted(int(p.name) for p in pkgdir.iterdir() if p.name.isdigit())
            if not versions:
                continue
            vdir = pkgdir / str(versions[-1])
        dirs.append(vdir)
    for vdir in dirs:
        for f in vdir.rglob("*.aidl"):
            text = strip_comments(f.read_text())
            pkg = re.search(r"package\s+([\w.]+);", text).group(1)
            m = re.search(r"\b(enum|parcelable|interface|union)\s+(\w+)", text)
            if m:
                files[f"{pkg}.{m.group(2)}"] = (m.group(1), pkg, m.group(2), text)
    kinds = {k: v[0] for k, v in files.items()}
    for full, (kind, pkg, name, text) in list(files.items()):
        if kind in ("parcelable", "union"):
            for nkind, nname, _ in split_nested(body_of(text))[0]:
                kinds[f"{full}.{nname}"] = nkind

    for full, (kind, pkg, name, text) in files.items():
        includes = []
        for d in deps(text, kinds, full, files):
            if kinds[d] != "interface" or kind != "interface":
                includes.append("aidl/" + path_of(d))
        forwards = []
        if kind == "interface":
            for d in deps(text, kinds, full, files):
                if kinds[d] == "interface":
                    dpkg, dname = d.rsplit(".", 1)
                    forwards.append((dpkg, dname))
        if kind == "enum":
            body = gen_enum(name, text)
        elif kind == "parcelable":
            body = gen_parcelable(name, text, kinds)
        elif kind == "union":
            body = gen_union(name, text, kinds)
        else:
            body = gen_interface(name, text, kinds)
        pre = []
        for dpkg, dname in forwards:
            pre += [f"}}  // namespace", f"namespace aidl::{dpkg.replace('.', '::')} {{ class {dname}; }}",
                    f"namespace aidl::{pkg.replace('.', '::')} {{"]
        target = out / "aidl" / path_of(full)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(header(pkg, name, includes, pre + body))
        if kind == "interface":
            bn = name[1:]
            (out / "aidl" / path_of(f"{pkg}.Bn{bn}")).write_text(header(
                pkg, f"Bn{bn}", ["aidl/" + path_of(full)],
                [f"class Bn{bn} : public ::ndk::BnCInterface<{name}> {{}};"]))


if __name__ == "__main__":
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    generate(Path(sys.argv[1]), int(sys.argv[2]), Path(sys.argv[3]), [Path(p) for p in sys.argv[4:]])
