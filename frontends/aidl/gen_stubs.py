"""Generate "not supported" base classes for the radio HAL interfaces.

    gen_stubs.py AIDL_API_DIR VERSION OUT_DIR

AIDL_API_DIR is hardware/interfaces/radio/aidl/aidl_api; VERSION the frozen
version to build against (5 for Android 17). For every IRadio<X> interface it
writes NotSupported<X>.h: a class deriving from BnRadio<X> that keeps the
response and indication callbacks and answers every request with
REQUEST_NOT_SUPPORTED. The real implementation overrides what it supports.

The output is checked in, so the Android build needs no Python.
"""
import re
import sys
from pathlib import Path

PRIMITIVES = {
    "int": "int32_t", "long": "int64_t", "boolean": "bool", "byte": "int8_t",
    "char": "char16_t", "float": "float", "double": "double", "void": "void",
}

INTERFACES = {
    # package suffix: interface name
    "config": "IRadioConfig",
    "data": "IRadioData",
    "messaging": "IRadioMessaging",
    "modem": "IRadioModem",
    "network": "IRadioNetwork",
    "sim": "IRadioSim",
    "voice": "IRadioVoice",
}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def index_types(api, version):
    """Map fully qualified type name -> kind (enum, parcelable, interface, union)."""
    kinds = {}
    for pkgdir in api.iterdir():
        vdir = pkgdir / str(version)
        if not vdir.is_dir():
            # Packages with fewer versions (ims): take their newest
            versions = sorted(int(p.name) for p in pkgdir.iterdir() if p.name.isdigit())
            if not versions:
                continue
            vdir = pkgdir / str(versions[-1])
        for f in vdir.rglob("*.aidl"):
            text = strip_comments(f.read_text())
            pkg = re.search(r"package\s+([\w.]+);", text).group(1)
            m = re.search(r"\b(enum|parcelable|interface|union)\s+(\w+)", text)
            if m:
                kinds[f"{pkg}.{m.group(2)}"] = m.group(1)
    return kinds


def cpp_type(aidl, kinds):
    nullable = aidl.startswith("@nullable ")
    if nullable:
        aidl = aidl[len("@nullable "):]
    array = aidl.endswith("[]")
    base = aidl[:-2] if array else aidl

    if base in PRIMITIVES:
        t = PRIMITIVES[base]
        if array and base == "byte":
            t = "uint8_t"
    elif base == "String":
        t = "std::string"
    elif "." in base:
        t = "::aidl::" + base.replace(".", "::")
        if kinds.get(base) == "interface":
            t = f"std::shared_ptr<{t}>"
    else:
        sys.exit(f"unknown type {aidl}")

    if array:
        t = f"std::vector<{t}>"
    if nullable and not t.startswith("std::shared_ptr"):
        t = f"std::optional<{t}>"

    by_value = (not array and not nullable and
                (base in PRIMITIVES or kinds.get(base) == "enum"))
    return t if by_value else f"const {t}&"


def parse_methods(path):
    text = strip_comments(path.read_text())
    body = text[text.index("{") + 1:text.rindex("}")]
    methods = []
    for m in re.finditer(r"(?:oneway\s+)?void\s+(\w+)\s*\(([^)]*)\)\s*;", body):
        params = []
        for p in filter(None, (s.strip() for s in m.group(2).split(","))):
            p = re.sub(r"^(in|out|inout)\s+", "", p)
            ptype, name = p.rsplit(None, 1)
            params.append((ptype, name))
        methods.append((m.group(1), params))
    return methods


def generate(api, version, out):
    kinds = index_types(api, version)
    out.mkdir(parents=True, exist_ok=True)

    for suffix, iface in INTERFACES.items():
        pkg = f"android.hardware.radio.{suffix}"
        base = api / pkg / str(version) / "android/hardware/radio" / suffix
        name = iface[1:]  # RadioSim
        requests = parse_methods(base / f"{iface}.aidl")
        responses = {m: p for m, p in parse_methods(base / f"{iface}Response.aidl")}
        ns = f"::aidl::android::hardware::radio::{suffix}"
        cls = f"NotSupported{name[len('Radio'):]}"

        lines = [
            "// SPDX-License-Identifier: GPL-2.0-or-later",
            f"// Generated by gen_stubs.py from {pkg} V{version}. Do not edit.",
            "#pragma once",
            "",
            f"#include <aidl/android/hardware/radio/{suffix}/Bn{name}.h>",
            f"#include <aidl/android/hardware/radio/{suffix}/{iface}Indication.h>",
            f"#include <aidl/android/hardware/radio/{suffix}/{iface}Response.h>",
            "",
            '#include "frontends/aidl/Response.h"',
            "",
            "namespace modemd::hal {",
            "",
            f"class {cls} : public {ns}::Bn{name} {{",
            "  public:",
            f"    ::ndk::ScopedAStatus setResponseFunctions(",
            f"            const std::shared_ptr<{ns}::{iface}Response>& response,",
            f"            const std::shared_ptr<{ns}::{iface}Indication>& indication) override {{",
            "        std::lock_guard<std::mutex> lock(callbacksLock_);",
            "        response_ = response;",
            "        indication_ = indication;",
            "        onResponseFunctionsSet();",
            "        return ::ndk::ScopedAStatus::ok();",
            "    }",
            "",
            "    ::ndk::ScopedAStatus responseAcknowledgement() override {",
            "        return ::ndk::ScopedAStatus::ok();",
            "    }",
            "",
        ]

        for method, params in requests:
            if method in ("setResponseFunctions", "responseAcknowledgement"):
                continue
            args = ", ".join(f"{cpp_type(t, kinds)} {n}" for t, n in params)
            lines.append(f"    ::ndk::ScopedAStatus {method}({args}) override {{")
            rname = f"{method}Response"
            if rname not in responses or not params or params[0][1] != "serial":
                lines += ["        return ::ndk::ScopedAStatus::ok();", "    }", ""]
                continue
            unused = [n for t, n in params[1:]]
            if unused:
                lines.append("        " + " ".join(f"(void){n};" for n in unused))
            extra = ", {}" * (len(responses[rname]) - 1)
            lines += [
                f"        if (auto r = response()) r->{rname}(notSupported(serial){extra});",
                "        return ::ndk::ScopedAStatus::ok();",
                "    }",
                "",
            ]

        lines += [
            "  protected:",
            "    virtual void onResponseFunctionsSet() {}",
            "",
            f"    std::shared_ptr<{ns}::{iface}Response> response() {{",
            "        std::lock_guard<std::mutex> lock(callbacksLock_);",
            "        return response_;",
            "    }",
            f"    std::shared_ptr<{ns}::{iface}Indication> indication() {{",
            "        std::lock_guard<std::mutex> lock(callbacksLock_);",
            "        return indication_;",
            "    }",
            "",
            "  private:",
            "    std::mutex callbacksLock_;",
            f"    std::shared_ptr<{ns}::{iface}Response> response_;",
            f"    std::shared_ptr<{ns}::{iface}Indication> indication_;",
            "};",
            "",
            "}  // namespace modemd::hal",
            "",
        ]
        (out / f"{cls}.h").write_text("\n".join(lines))
        print(f"{cls}.h: {len(requests)} methods")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    generate(Path(sys.argv[1]), int(sys.argv[2]), Path(sys.argv[3]))
